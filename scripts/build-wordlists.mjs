/**
 * Downloads frequency word lists and writes data/{lang}.json for the typing test.
 * Source: https://github.com/hermitdave/FrequencyWords (MIT-style community data)
 * Run: node scripts/build-wordlists.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const OUT_DIR = path.join(ROOT, "data");
const TARGET_WORDS = 5000;
const BASE =
  "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018";

/** Maps UI code -> path under content/2018 */
const LANGS = [
  { code: "en", path: "en/en_50k.txt" },
  { code: "de", path: "de/de_50k.txt" },
  { code: "fr", path: "fr/fr_50k.txt" },
  { code: "es", path: "es/es_50k.txt" },
  { code: "it", path: "it/it_50k.txt" },
  { code: "pt", path: "pt_br/pt_br_50k.txt" },
  { code: "nl", path: "nl/nl_50k.txt" },
  { code: "pl", path: "pl/pl_50k.txt" },
  { code: "tr", path: "tr/tr_50k.txt" },
  { code: "sv", path: "sv/sv_50k.txt" }
];

function parseWords(text) {
  const words = [];
  const seen = new Set();
  const lines = text.split(/\r?\n/);
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    const first = trimmed.split(/\s+/)[0];
    if (!first || /^\d+$/.test(first)) continue;
    const w = first.normalize("NFC").toLowerCase();
    if (seen.has(w)) continue;
    seen.add(w);
    words.push(w);
    if (words.length >= TARGET_WORDS) break;
  }
  return words;
}

/** Writes ../word-banks.js so the typing test works without HTTP (e.g. file://). */
function writeWordBanksFromDisk() {
  const bank = {};
  for (const { code } of LANGS) {
    const fp = path.join(OUT_DIR, `${code}.json`);
    if (!fs.existsSync(fp)) {
      console.error(`Missing ${path.relative(ROOT, fp)}`);
      process.exitCode = 1;
      continue;
    }
    const payload = JSON.parse(fs.readFileSync(fp, "utf8"));
    if (!Array.isArray(payload.words) || payload.words.length === 0) {
      console.error(`Empty words in ${code}`);
      process.exitCode = 1;
      continue;
    }
    bank[code] = payload.words;
  }
  const outPath = path.join(ROOT, "word-banks.js");
  const banner = "/* Generated by: node scripts/build-wordlists.mjs --embed-only — do not edit */\n";
  fs.writeFileSync(outPath, `${banner}globalThis.__DUCK_WORD_BANKS=${JSON.stringify(bank)};\n`);
  console.log(`Wrote ${path.relative(ROOT, outPath)}`);
}

async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });

  for (const { code, path: rel } of LANGS) {
    const url = `${BASE}/${rel}`;
    process.stdout.write(`Fetching ${code} … `);
    const res = await fetch(url);
    if (!res.ok) {
      console.error(`HTTP ${res.status}`);
      process.exitCode = 1;
      continue;
    }
    const text = await res.text();
    const words = parseWords(text);
    const outPath = path.join(OUT_DIR, `${code}.json`);
    const payload = { lang: code, words, count: words.length };
    fs.writeFileSync(outPath, JSON.stringify(payload));
    console.log(`${words.length} words → ${path.relative(ROOT, outPath)}`);
  }
  writeWordBanksFromDisk();
}

if (process.argv.includes("--embed-only")) {
  writeWordBanksFromDisk();
  process.exit(process.exitCode ?? 0);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
